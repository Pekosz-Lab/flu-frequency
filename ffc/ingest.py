"""Stage 1: offline ingestion.

Reads ONLY the manifest, the Auspice JSONs it lists and their optional
tip-frequency / root-sequence sidecars. Makes no network calls.

Per build it writes Parquet files to <store>/parquet/<table>/<build_id>.parquet
(re-used if the source files are unchanged), then assembles <store>/ffc.duckdb
and precomputes clade/subclade frequency trajectories and every compatible
local-vs-global comparison.
"""

