GEO_COLS = ["region", "country", "division", "location", "host"]


class IngestError(RuntimeError):
    pass


def _sha256(path: Path | None) -> str | None:
    if not path or not path.exists():
        return None
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _sidecar(main: Path, suffix: str) -> Path | None:
    cand = main.with_name(main.stem + suffix)
    return cand if cand.exists() else None


def _now() -> str:
    return dt.datetime.now().astimezone().isoformat(timespec="seconds")


def _pick_field(tips, candidates: list[str]) -> str | None:
    for c in candidates:
        if any(c in t.attrs for t in tips):
            return c
    return None


def ingest_build(entry: BuildEntry, settings: dict, log) -> dict[str, pd.DataFrame]:
    """Parse one build into per-table DataFrames."""
    bid = entry.id
    with open(entry.auspice_json) as fh:
        d = json.load(fh)
    rep = validate_auspice(d)
    if not rep.ok:
        raise IngestError(f"{bid}: invalid Auspice JSON: " + "; ".join(rep.errors))
    warnings = list(rep.warnings)
    pb = parse_build(d)
    tip_names = [t.name for t in pb.tips]
    dated = {t.name: t.num_date for t in pb.tips if t.num_date is not None}

    # ---- frequencies (priority: frequency JSON > embedded > recompute)
    freq_path = entry.frequencies_json
    freq_detail = None
    if freq_path is None:
        freq_path = _sidecar(entry.auspice_json, "_tip-frequencies.json")
        if freq_path:
            freq_detail = f"auto-detected sidecar {freq_path.name}"
    elif not freq_path.exists():
        warnings.append(f"frequencies_json {freq_path} not found; falling back.")
        freq_path = None
    source = None
    pivots = weights = projection = None
    if freq_path:
        with open(freq_path) as fh:
            fj = json.load(fh)
        frep = validate_tip_frequencies(fj, set(tip_names))
        warnings += frep.warnings
        if frep.ok:
            pivots, weights, projection = import_tip_frequencies(fj, tip_names)
            source = "imported"
            freq_detail = freq_detail or f"{freq_path.name}"
            gen = fj.get("generated_by")
            if isinstance(gen, dict):
                freq_detail += f" (generated by {gen.get('program', '?')} {gen.get('version', '')})".rstrip()
        else:
            warnings.append("Frequency JSON rejected: " + "; ".join(frep.errors) + " Falling back.")
            freq_path = None
    if source is None and pb.embedded_frequencies:
        frep = validate_tip_frequencies(pb.embedded_frequencies, set(tip_names))
        warnings += frep.warnings
        if frep.ok:
            pivots, weights, projection = import_tip_frequencies(pb.embedded_frequencies, tip_names)
            source = "embedded"
            freq_detail = "frequency block embedded in the Auspice JSON"
    if source is None:
        if not dated:
            raise IngestError(f"{bid}: no dated tips and no frequency data; cannot compute frequencies.")
        rc = settings["recompute"]
        pivots, weights = recompute_tip_frequencies(
            dated,
            narrow_bandwidth=float(rc["narrow_bandwidth"]),
            wide_bandwidth=float(rc["wide_bandwidth"]),
            proportion_wide=float(rc["proportion_wide"]),
            pivot_interval_months=int(rc["pivot_interval_months"]),
        )
        source = "recomputed"
        freq_detail = (
            "KDE recomputed from tip collection dates (augur kde defaults: narrow "
            f"{float(rc['narrow_bandwidth']):.4f} y, wide {float(rc['wide_bandwidth']):.4f} y, "
            f"proportion wide {rc['proportion_wide']}, {rc['pivot_interval_months']}-month pivots)"
        )

    # ---- root sequence sidecar (optional, for genotype root states)
    root_path = entry.root_sequence_json or _sidecar(entry.auspice_json, "_root-sequence.json")
    root_seq = None
    if root_path and root_path.exists():
        with open(root_path) as fh:
            root_seq = json.load(fh)
        if not isinstance(root_seq, dict):
            warnings.append("root-sequence JSON is not an object; ignored.")
            root_seq = None

    clade_field = _pick_field(pb.tips, settings["grouping_fields"]["clade"])
    subclade_field = _pick_field(pb.tips, settings["grouping_fields"]["subclade"])
    if not clade_field:
        warnings.append("No clade field found in node_attrs; clade grouping will show 'Not assigned'.")
    if not subclade_field:
        warnings.append("No subclade field found in node_attrs; subclade grouping will show 'Not assigned'.")

    # ---- genotypes
    roots = root_states(pb, root_seq)
    gt_rows = tip_genotypes(pb, roots)
    pos_rows = position_summary(roots, gt_rows, len(pb.tips))
    per_tip_gt: dict[str, dict] = {}
    for tip, gene, pos, st in gt_rows:
        per_tip_gt.setdefault(tip, {}).setdefault(gene, {})[str(pos)] = st

    # ---- metadata filter fields
    mf = settings["metadata_filters"]
    meta_filters = set(pb.meta.get("filters") or []) if mf.get("include_json_filters") else set()
    cat_colorings = {
        k for k, c in pb.colorings.items() if c["type"] in ("categorical", "ordinal", "boolean")
    } if mf.get("include_categorical_colorings") else set()
    candidates = (meta_filters | cat_colorings | set(mf.get("extra_candidates") or [])) - set(mf.get("exclude") or [])
    field_rows, attr_rows = [], []
    for fname in sorted(candidates):
        vals = Counter(str(t.attrs[fname]) for t in pb.tips if fname in t.attrs)
        if not vals:
            continue
        if len(vals) > int(mf.get("max_distinct_values", 400)):
            warnings.append(f"Field '{fname}' has {len(vals)} distinct values; not offered as a filter.")
            continue
        locs = [f"tree.node_attrs.{fname}"]
        if fname in pb.colorings:
            locs.append("meta.colorings")
        if fname in meta_filters:
            locs.append("meta.filters")
        field_rows.append(
            {
                "build_id": bid,
                "field_name": fname,
                "field_title": pb.colorings.get(fname, {}).get("title", fname),
                "field_type": pb.colorings.get(fname, {}).get("type", "categorical"),
                "allowed_values": json.dumps([{"value": v, "count": n} for v, n in sorted(vals.items())]),
                "n_tips_with_value": sum(vals.values()),
                "source_location_in_json": ", ".join(locs),
            }
        )
        attr_rows += [
            {"build_id": bid, "tip_id": t.name, "field": fname, "value": str(t.attrs[fname])}
            for t in pb.tips
            if fname in t.attrs
        ]

    # ---- tips
    tip_rows = []
    for t in pb.tips:
        tip_rows.append(
            {
                "build_id": bid,
                "tip_id": t.name,
                "parent_node_id": t.parent,
                "num_date": t.num_date,
                "collection_date": from_decimal(t.num_date) if t.num_date is not None else None,
                **{c: (str(t.attrs[c]) if c in t.attrs else None) for c in GEO_COLS},
                "clade": str(t.attrs[clade_field]) if clade_field and clade_field in t.attrs else None,
                "subclade": str(t.attrs[subclade_field]) if subclade_field and subclade_field in t.attrs else None,
                "metadata_json": json.dumps(t.attrs, default=str),
                "genotype_annotations_json": json.dumps(per_tip_gt.get(t.name, {})),
                "pivot_bin": pivot_bins(pivots, t.num_date),
            }
        )

    # ---- tip frequencies (sparse)
    tf_rows = []
    for t, w in weights.items():
        for i, x in enumerate(w):
            if x > 1e-9:
                tf_rows.append({"build_id": bid, "tip_id": t, "pivot_idx": i, "weight": float(x)})

    dates = [t.num_date for t in pb.tips if t.num_date is not None]
    min_d = from_decimal(min(dates)) if dates else None
    max_d = from_decimal(max(dates)) if dates else None
    ann_rows = []
    for gene, a in pb.genome_annotations.items():
        if not isinstance(a, dict):
            continue
        start, end = a.get("start"), a.get("end")
        if start is None and isinstance(a.get("segments"), list) and a["segments"]:
            start, end = a["segments"][0].get("start"), a["segments"][-1].get("end")
        ann_rows.append(
            {
                "build_id": bid,
                "gene": gene,
                "start_pos": start,
                "end_pos": end,
                "strand": a.get("strand"),
                "seq_type": a.get("type") or ("nuc" if gene == "nuc" else "aa"),
                "has_mutations": gene in roots,
            }
        )
    for gene in roots:
        if gene not in pb.genome_annotations:
            warnings.append(f"Mutations found for '{gene}' but it has no genome annotation; genotype option hidden.")

    manifest_meta = entry.manifest_metadata()
    builds_row = {
        "build_id": bid,
        "source_type": entry.source_type,
        "organization": entry.organization,
        "display_name": entry.label,
        "subtype": entry.subtype,
        "segment": entry.segment,
        "resolution": entry.resolution,
        "auspice_json_path": str(entry.auspice_json),
        "frequencies_json_path": str(freq_path) if freq_path else None,
        "root_sequence_json_path": str(root_path) if root_seq else None,
        "manifest_metadata": json.dumps(manifest_meta, default=str),
        "json_metadata": json.dumps(trimmed_meta(pb.meta), default=str),
        "json_title": pb.meta.get("title"),
        "build_date": entry.build_date,
        "updated_date": pb.meta.get("updated"),
        "most_recent_sample_date": max_d,
        "min_sample_date": min_d,
        "max_sample_date": max_d,
        "total_tip_count": len(pb.tips),
        "dated_tip_count": len(dated),
        "tips_with_frequency": len(weights),
        "downsampling_description": entry.downsampling,
        "frequency_source": source,
        "frequency_source_detail": freq_detail,
        "pivot_count": len(pivots),
        "projection_pivot": projection,
        "clade_field": clade_field,
        "subclade_field": subclade_field,
        "ingestion_timestamp": _now(),
        "source_json_version": d.get("version"),
        "source_sha256": None,  # filled by caller
        "remote": entry.remote,
        "fetched_at": entry.fetched_at,
        "synthetic": entry.synthetic,
        "validation_warnings": json.dumps(warnings),
    }
    if projection is not None:
        warnings.append(f"Frequencies after projection pivot {projection:.3f} are projections and are hidden by default.")
        builds_row["validation_warnings"] = json.dumps(warnings)
    log(f"  {bid}: {len(pb.tips)} tips, {len(pivots)} pivots, frequencies {source}, "
        f"clade field {clade_field!r}, subclade field {subclade_field!r}, {len(field_rows)} filter fields")
    for w in warnings:
        log(f"    warning: {w}")

    return {
        "builds": pd.DataFrame([builds_row]),
        "tips": pd.DataFrame(tip_rows),
        "tip_attrs": pd.DataFrame(attr_rows),
        "pivots": pd.DataFrame(pivot_table_rows(bid, pivots, projection)),
        "tip_frequencies": pd.DataFrame(tf_rows),
        "tip_genotypes": pd.DataFrame(gt_rows, columns=["tip_id", "gene", "position", "state"]).assign(build_id=bid),
        "genotype_positions": pd.DataFrame(
            [{**r, "build_id": bid, "state_counts": json.dumps(r["state_counts"])} for r in pos_rows]
        ),
        "gene_annotations": pd.DataFrame(ann_rows),
        "root_sequences": pd.DataFrame(
            [{"build_id": bid, "gene": g, "sequence": s} for g, s in (root_seq or {}).items() if isinstance(s, str)]
        ),
        "value_order": pd.DataFrame(value_order_rows(bid, pb, settings)),
        "color_scales": pd.DataFrame(
            [
                {"build_id": bid, "coloring_key": k, "value": v, "color": c}
                for k, col in pb.colorings.items()
                for v, c in col["scale"].items()
            ]
        ),
        "available_metadata_fields": pd.DataFrame(field_rows),
    }


def value_order_rows(bid: str, pb, settings: dict) -> list[dict]:
    """Clade/subclade values over all nodes in pre-order (Auspice's ordering inputs)."""
    from .colors import is_valid_value

    keys = {k for cands in settings["grouping_fields"].values() for k in cands}
    first: dict[tuple, int] = {}
    count: Counter = Counter()
    for i, n in enumerate(pb.nodes):
        for k in keys:
            v = n.attrs.get(k)
            if v is None or not is_valid_value(v):
                continue
            first.setdefault((k, str(v)), i)
            count[(k, str(v))] += 1
    return [
        {"build_id": bid, "coloring_key": k, "value": v, "first_index": idx, "n_nodes": count[(k, v)]}
        for (k, v), idx in sorted(first.items(), key=lambda x: x[1])
    ]


def load_reference_colors(colors_path: Path) -> pd.DataFrame:
    """National colour scales written by `ffc fetch` (data/colors/nextstrain_colors.json)."""
    if not colors_path.exists():
        return pd.DataFrame()
    data = json.loads(colors_path.read_text())
    rows = []
    for lineage, entry in (data.get("lineages") or {}).items():
        st, seg = lineage.split("/")
        srcs = json.dumps(entry.get("sources", []))
        for key, scale in (entry.get("keys") or {}).items():
            for rank, (v, c) in enumerate(scale):
                rows.append({"subtype": st, "segment": seg.upper(), "coloring_key": key, "value": v,
                             "color": c, "rank": rank, "sources": srcs, "fetched_at": data.get("fetched_at")})
    return pd.DataFrame(rows)


def _write_parquet(df: pd.DataFrame, table: str, path: Path):
    cols = columns(table)
    for c in cols:
        if c not in df.columns:
            df[c] = None
    df = df[cols]
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    con = duckdb.connect()
    con.execute(f"CREATE TABLE t ({SCHEMAS[table]})")
    if not df.empty:
        con.register("df", df)
        con.execute("INSERT INTO t SELECT * FROM df")
    con.execute(f"COPY t TO '{tmp.as_posix()}' (FORMAT PARQUET, COMPRESSION ZSTD)")
    con.close()
    os.replace(tmp, path)


def run_ingest(manifest_path: Path, store: Path, settings_path: Path | None = None,
               harmonization_path: Path | None = None, force: bool = False, log=print,
               colors_path: Path | None = None) -> dict:
    settings = load_settings(settings_path)
    entries = [e for e in load_manifest(manifest_path) if e.active]
    enabled = set(settings["enabled_segments"])
    skipped_seg = [e.id for e in entries if e.segment not in enabled]
    entries = [e for e in entries if e.segment in enabled]
    if skipped_seg:
        log(f"Skipping builds of segments not enabled in settings: {', '.join(skipped_seg)}")
    store.mkdir(parents=True, exist_ok=True)
    pq = store / "parquet"
    hashes_path = pq / "_source_hashes.json"
    old_hashes = json.loads(hashes_path.read_text()) if hashes_path.exists() else {}
    settings_sig = hashlib.sha1(json.dumps(settings, sort_keys=True, default=str).encode()).hexdigest()
    new_hashes = {}
    report = {"started": _now(), "builds": {}, "app_version": __version__}

    for e in entries:
        missing = [str(p) for p in (e.auspice_json,) if not p.exists()]
        if missing:
            log(f"  {e.id}: SKIPPED, file not found: {missing[0]}")
            report["builds"][e.id] = {"status": "missing_file", "error": f"Not found: {missing[0]}"}
            continue
        freq = e.frequencies_json or _sidecar(e.auspice_json, "_tip-frequencies.json")
        root = e.root_sequence_json or _sidecar(e.auspice_json, "_root-sequence.json")
        sig = {
            "auspice": _sha256(e.auspice_json),
            "freq": _sha256(freq),
            "root": _sha256(root),
            "manifest": hashlib.sha1(json.dumps(e.__dict__, default=str, sort_keys=True).encode()).hexdigest(),
            "settings": settings_sig,
            "app": __version__,
        }
        new_hashes[e.id] = sig
        have_all = all((pq / t / f"{e.id}.parquet").exists() for t in PER_BUILD_TABLES)
        if not force and old_hashes.get(e.id) == sig and have_all:
            log(f"  {e.id}: unchanged, reusing stored tables")
            report["builds"][e.id] = {"status": "unchanged"}
            continue
        try:
            tables = ingest_build(e, settings, log)
        except (IngestError, json.JSONDecodeError, KeyError, ValueError) as exc:
            log(f"  {e.id}: FAILED: {exc}")
            report["builds"][e.id] = {"status": "failed", "error": str(exc)}
            new_hashes.pop(e.id, None)
            continue
        tables["builds"]["source_sha256"] = sig["auspice"]
        for t, df in tables.items():
            _write_parquet(df, t, pq / t / f"{e.id}.parquet")
        report["builds"][e.id] = {
            "status": "ingested",
            "warnings": json.loads(tables["builds"].validation_warnings.iloc[0]),
        }
    hashes_path.parent.mkdir(parents=True, exist_ok=True)
    hashes_path.write_text(json.dumps(new_hashes, indent=1))

    ok_ids = [i for i, r in report["builds"].items() if r["status"] in ("ingested", "unchanged")]
    # remove stale per-build files (builds no longer active in the manifest)
    for t in PER_BUILD_TABLES:
        d = pq / t
        if d.exists():
            for f in d.glob("*.parquet"):
                if f.stem not in ok_ids:
                    f.unlink()

    if colors_path is None:
        colors_path = manifest_path.resolve().parent.parent / "data" / "colors" / "nextstrain_colors.json"
    assemble(store, ok_ids, load_harmonization(harmonization_path), log, colors_path)
    report["finished"] = _now()
    (store / "ingest_report.json").write_text(json.dumps(report, indent=1))
    return report


def assemble(store: Path, build_ids: list[str], harmonization: dict, log=print,
             colors_path: Path | None = None) -> None:
    """Load per-build Parquet into a fresh DuckDB file and precompute."""
    pq = store / "parquet"
    tmp = store / "ffc.duckdb.tmp"
    if tmp.exists():
        tmp.unlink()
    con = duckdb.connect(str(tmp))
    for t in PER_BUILD_TABLES + DERIVED_TABLES:
        con.execute(f"CREATE TABLE {t} ({SCHEMAS[t]})")
    for t in PER_BUILD_TABLES:
        files = [(pq / t / f"{b}.parquet").as_posix() for b in build_ids if (pq / t / f"{b}.parquet").exists()]
        if files:
            con.execute(f"INSERT INTO {t} BY NAME SELECT * FROM read_parquet(?)", [files])
    ref = load_reference_colors(colors_path) if colors_path else pd.DataFrame()
    if not ref.empty:
        con.register("ref", ref)
        con.execute("INSERT INTO reference_colors BY NAME SELECT * FROM ref")
        con.unregister("ref")
        log(f"National colours loaded from {colors_path} (fetched {ref.fetched_at.iloc[0]})")
    else:
        log("No fetched national colours (data/colors/nextstrain_colors.json); using each global build's own scale.")
    # Precompute (unfiltered clade/subclade trajectories, then comparisons)
    eng = Engine.from_connection(con, harmonization)
    builds = con.execute("SELECT build_id, source_type, subtype, segment, frequency_source FROM builds").df()
    obs = []
    for b in builds.itertuples():
        for grouping in ("clade", "subclade"):
            df, _ = eng._frequencies(Query(b.build_id, grouping))
            if df.empty:
                continue
            obs.append(
                pd.DataFrame(
                    {
                        "build_id": b.build_id,
                        "source_type": b.source_type,
                        "subtype": b.subtype,
                        "segment": b.segment,
                        "grouping_type": grouping,
                        "genotype_definition": None,
                        "taxon_label": df.taxon,
                        "pivot_idx": df.pivot_idx,
                        "date_bin": df.date,
                        "num_date": df.num_date,
                        "month": df.month,
                        "is_projection": df.is_projection,
                        "frequency": df.frequency,
                        "numerator_count": df.numerator,
                        "denominator_count": df.denominator,
                        "filter_context_hash": "unfiltered",
                        "calculation_method": f"kde_tip_frequencies:{b.frequency_source}",
                    }
                )
            )
    if obs:
        allobs = pd.concat(obs, ignore_index=True)
        con.register("allobs", allobs)
        con.execute("INSERT INTO frequency_observations BY NAME SELECT * FROM allobs")
        con.unregister("allobs")
    eng._cache.clear()
    comps = []
    loc = builds[builds.source_type == "local"]
    glo = builds[builds.source_type == "global"]
    for lb in loc.itertuples():
        for gb in glo[(glo.subtype == lb.subtype) & (glo.segment == lb.segment)].itertuples():
            for grouping in ("clade", "subclade"):
                ldf, _ = eng.frequencies(Query(lb.build_id, grouping))
                gdf, _ = eng.frequencies(Query(gb.build_id, grouping))
                a, _ = eng.aligned_frame(lb.build_id, gb.build_id, ldf[~ldf.is_projection.astype(bool)],
                                         gdf[~gdf.is_projection.astype(bool)])
                if a.empty or not a.both.any():
                    continue
                a = a[a.both]
                comps.append(
                    pd.DataFrame(
                        {
                            "local_build_id": lb.build_id,
                            "global_build_id": gb.build_id,
                            "subtype": lb.subtype,
                            "segment": lb.segment,
                            "grouping_type": grouping,
                            "genotype_definition": None,
                            "taxon_label": a.taxon,
                            "date_bin": a.grid_date.dt.date.astype(str),
                            "local_frequency": a.frequency_local,
                            "global_frequency": a.frequency_global,
                            "difference_percentage_points": a.difference_pp,
                            "local_numerator_count": a.numerator_local,
                            "local_denominator_count": a.denominator_local,
                            "global_numerator_count": a.numerator_global,
                            "global_denominator_count": a.denominator_global,
                            "local_pivot_date": a.pivot_date_local,
                            "global_pivot_date": a.pivot_date_global,
                            "alignment_method": "shared_timepoints_nearest_pivot",
                            "filter_context_hash": "unfiltered",
                        }
                    )
                )
    if comps:
        allc = pd.concat(comps, ignore_index=True)
        con.register("allc", allc)
        con.execute("INSERT INTO comparison_observations BY NAME SELECT * FROM allc")
        con.unregister("allc")
    for t in DERIVED_TABLES:
        con.execute(f"COPY {t} TO '{(pq / (t + '.parquet')).as_posix()}' (FORMAT PARQUET, COMPRESSION ZSTD)")
    con.execute(
        "CREATE TABLE store_info AS SELECT ? AS built_at, ? AS app_version, ? AS alignment_method",
        [_now(), __version__, ALIGNMENT_METHOD],
    )
    n_b = con.execute("SELECT COUNT(*) FROM builds").fetchone()[0]
    n_c = con.execute("SELECT COUNT(DISTINCT local_build_id || global_build_id) FROM comparison_observations").fetchone()[0]
    con.close()
    final = store / "ffc.duckdb"
    os.replace(tmp, final)
    shutil.rmtree(store / "ffc.duckdb.tmp.wal", ignore_errors=True)
    log(f"Store ready: {final} ({n_b} builds, {n_c} precomputed local/global pairs)")
